-- Admin "Announcements": an e-mail broadcast (one user or everyone) typed by the admin. Recipients are stored per row so a long send
-- can be resumed after a restart and the admin can see progress.
CREATE TABLE announcements (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id    BIGINT,
  subject     TEXT   NOT NULL,
  message     TEXT   NOT NULL,
  audience    TEXT   NOT NULL,                 -- 'all' | 'user'
  total       INTEGER NOT NULL DEFAULT 0,
  sent        INTEGER NOT NULL DEFAULT 0,
  failed      INTEGER NOT NULL DEFAULT 0,
  status      TEXT   NOT NULL DEFAULT 'sending',   -- sending | done | stopped
  note        TEXT,
  created_at  BIGINT NOT NULL,
  finished_at BIGINT
);
CREATE INDEX ix_announcements_time ON announcements (created_at DESC);
CREATE TABLE announcement_recipients (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  announcement_id BIGINT NOT NULL REFERENCES announcements(id) ON DELETE CASCADE,
  email           TEXT   NOT NULL,
  name            TEXT,
  status          TEXT   NOT NULL DEFAULT 'pending',   -- pending | sent | failed
  error           TEXT
);
CREATE INDEX ix_annrec_status ON announcement_recipients (announcement_id, status);
