-- PostgreSQL schema for UnknownXfam Gateway.
-- This is the final shape of the original Cloudflare D1 migrations 0001-0005 (same tables, columns, defaults,
-- CHECK constraints, unique/partial indexes and statuses), translated to PostgreSQL:
--   INTEGER PRIMARY KEY AUTOINCREMENT -> BIGINT identity;  unix-second timestamps / paise -> BIGINT;
--   COLLATE NOCASE                    -> expression indexes on LOWER(...) (queries use LOWER(x) = LOWER(?)).

CREATE TABLE users (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                TEXT NOT NULL,
  email               TEXT NOT NULL,
  email_canon         TEXT NOT NULL,              -- Gmail dots/+tags removed: one mailbox = one account
  pass_hash           TEXT NOT NULL,              -- pbkdf2$<iterations>$<salt>$<hash>
  approval            TEXT NOT NULL DEFAULT 'pending' CHECK (approval IN ('pending','approved','rejected')),
  email_verified      INTEGER NOT NULL DEFAULT 0,
  upi                 TEXT,
  api_key_hash        TEXT,                       -- sha256(key): used for lookup, the key is never stored in clear
  api_key_enc         TEXT,                       -- AES-GCM sealed key so the OWNER can view it (admins cannot)
  api_key_prefix      TEXT,
  webhook_secret_hash TEXT,
  webhook_secret_enc  TEXT,
  created_at          BIGINT NOT NULL,
  decided_at          BIGINT,
  role                TEXT NOT NULL DEFAULT 'USER' CHECK (role IN ('USER','SUPPORT','ADMIN','SUPER_ADMIN')),
  acct_status         TEXT NOT NULL DEFAULT 'active' CHECK (acct_status IN ('active','frozen','suspended','banned')),
  suspended_until     BIGINT,                     -- unix seconds; the suspension ends automatically
  status_reason       TEXT,
  status_changed_at   BIGINT,
  api_enabled         INTEGER NOT NULL DEFAULT 1,
  session_version     INTEGER NOT NULL DEFAULT 0, -- bump = every existing session dies
  last_login_at       BIGINT,
  last_known_balance  BIGINT,                     -- paise; set after each verified payment that reports a balance
  last_balance_at     BIGINT,
  api_key_expires_at  BIGINT,                     -- unix seconds; NULL = never expires
  api_key_issued_at   BIGINT,
  api_key_custom      INTEGER NOT NULL DEFAULT 0  -- 1 = admin supplied the literal value
);
CREATE UNIQUE INDEX ux_users_email  ON users (LOWER(email));
CREATE UNIQUE INDEX ux_users_canon  ON users (email_canon);
CREATE UNIQUE INDEX ux_users_upi    ON users (LOWER(upi)) WHERE upi IS NOT NULL;
CREATE UNIQUE INDEX ux_users_apikey ON users (api_key_hash) WHERE api_key_hash IS NOT NULL;
CREATE UNIQUE INDEX ux_users_whsec  ON users (webhook_secret_hash) WHERE webhook_secret_hash IS NOT NULL;
CREATE INDEX ix_users_status ON users (acct_status, approval);
CREATE INDEX ix_users_role   ON users (role);

CREATE TABLE orders (
  id                  TEXT PRIMARY KEY,           -- ORDER_XXXXXXXXXXXX
  payment_id          TEXT NOT NULL,              -- PAY_XXXXXXXXXXXX
  user_id             BIGINT NOT NULL REFERENCES users(id),
  upi                 TEXT NOT NULL,
  payee_name          TEXT,
  amount              BIGINT NOT NULL,            -- paise requested
  pay_amount          BIGINT NOT NULL,            -- paise to pay (unique among a merchant's open orders)
  currency            TEXT NOT NULL DEFAULT 'INR',
  status              TEXT NOT NULL DEFAULT 'PENDING'
                       CHECK (status IN ('PENDING','PROCESSING','PAID','UNSUCCESSFUL','EXPIRED','CANCELLED','MANUAL_REVIEW')),
  created_at          BIGINT NOT NULL,
  expires_at          BIGINT NOT NULL,
  updated_at          BIGINT NOT NULL,
  paid_at             BIGINT,
  txn_ref             TEXT,                       -- UTR
  transaction_id      TEXT,                       -- bank/provider transaction id (may differ from the UTR)
  received_from       TEXT,
  purpose             TEXT,
  provider            TEXT,
  updated_balance     BIGINT,                     -- paise, from the notification, if present
  payment_time        BIGINT,
  verification_method TEXT,                       -- provider_webhook | provider_api | gmail_notification | manual_confirm
  verification_meta   TEXT
);
CREATE UNIQUE INDEX ux_orders_payment     ON orders (payment_id);
CREATE UNIQUE INDEX ux_orders_txn         ON orders (user_id, txn_ref) WHERE txn_ref IS NOT NULL;
-- Race-free "one open order per amount": concurrent creates cannot both get the same paise amount.
CREATE UNIQUE INDEX ux_orders_open_amount ON orders (user_id, pay_amount) WHERE status IN ('PENDING','PROCESSING');
CREATE INDEX ix_orders_user        ON orders (user_id, created_at DESC);
CREATE INDEX ix_orders_status      ON orders (status, expires_at);
CREATE INDEX ix_orders_txn_global  ON orders (txn_ref);
CREATE INDEX ix_orders_txid_global ON orders (transaction_id);
CREATE INDEX ix_orders_id_lower    ON orders (LOWER(id));          -- case-insensitive order lookups (old COLLATE NOCASE)
CREATE INDEX ix_orders_pid_lower   ON orders (LOWER(payment_id));

CREATE TABLE payment_events (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source     TEXT NOT NULL,
  event_key  TEXT NOT NULL,
  order_id   TEXT,
  user_id    BIGINT,
  result     TEXT NOT NULL,
  detail     TEXT,
  created_at BIGINT NOT NULL,
  UNIQUE (source, event_key)
);

CREATE TABLE app_settings (k TEXT PRIMARY KEY, v TEXT NOT NULL);

CREATE TABLE gmail_accounts (
  user_id           BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  email             TEXT NOT NULL,
  refresh_token_enc TEXT NOT NULL,                -- AES-GCM sealed, server-side only
  scope             TEXT,
  connected_at      BIGINT NOT NULL,
  last_checked      BIGINT
);
CREATE UNIQUE INDEX ux_gmail_email ON gmail_accounts (LOWER(email));

CREATE TABLE audit_log (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id       BIGINT,                          -- NULL = system (e.g. a suspension expired)
  target_user_id BIGINT,
  action         TEXT NOT NULL,
  reason         TEXT,
  ip             TEXT,
  metadata       TEXT,                            -- JSON; secrets are stripped before writing
  created_at     BIGINT NOT NULL
);
CREATE INDEX ix_audit_time   ON audit_log (created_at DESC);
CREATE INDEX ix_audit_target ON audit_log (target_user_id, created_at DESC);
CREATE INDEX ix_audit_admin  ON audit_log (admin_id, created_at DESC);

CREATE TABLE order_events (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   TEXT NOT NULL,
  type       TEXT NOT NULL,
  source     TEXT,
  detail     TEXT,
  created_at BIGINT NOT NULL
);
CREATE INDEX ix_order_events ON order_events (order_id, id);

CREATE TABLE api_activity (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT NOT NULL,
  endpoint    TEXT NOT NULL,
  method      TEXT NOT NULL,
  status_code INTEGER NOT NULL,
  ip          TEXT,
  order_id    TEXT,
  created_at  BIGINT NOT NULL
);
CREATE INDEX ix_api_activity ON api_activity (user_id, id DESC);

CREATE TABLE sessions (
  id              TEXT PRIMARY KEY,                -- HMAC of the cookie token (the token itself is never stored)
  user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at      BIGINT NOT NULL,
  expires_at      BIGINT NOT NULL,
  last_seen       BIGINT NOT NULL,
  ip              TEXT,
  ua              TEXT,
  session_version INTEGER NOT NULL
);
CREATE INDEX ix_sessions_user ON sessions (user_id);
CREATE INDEX ix_sessions_exp  ON sessions (expires_at);

CREATE TABLE rate_limits (
  k          TEXT PRIMARY KEY,                     -- "<rule>:<subject>:<window index>"
  count      INTEGER NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX ix_rate_exp ON rate_limits (expires_at);

CREATE TABLE email_otps (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      TEXT NOT NULL,
  purpose    TEXT NOT NULL CHECK (purpose IN ('signup','login','reset')),
  user_id    BIGINT,
  code_hash  TEXT NOT NULL,                        -- salted HMAC, never the code
  salt       TEXT NOT NULL,
  expires_at BIGINT NOT NULL,
  attempts   INTEGER NOT NULL DEFAULT 0,
  used       INTEGER NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL
);
CREATE INDEX ix_otp_lookup ON email_otps (email, purpose, created_at);

CREATE TABLE oauth_states (
  state_hash   TEXT PRIMARY KEY,
  user_id      BIGINT NOT NULL,
  kind         TEXT NOT NULL,                      -- gmail_user | gmail_sender
  verifier_enc TEXT NOT NULL,                      -- PKCE verifier, sealed
  extra        TEXT,
  created_at   BIGINT NOT NULL,
  expires_at   BIGINT NOT NULL
);

CREATE TABLE security_events (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT,
  type       TEXT NOT NULL,
  ip         TEXT,
  ua         TEXT,
  meta       TEXT,
  created_at BIGINT NOT NULL
);
CREATE INDEX ix_secevents_user ON security_events (user_id, id DESC);

CREATE TABLE payments (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id            TEXT NOT NULL REFERENCES orders(id),
  user_id             BIGINT NOT NULL REFERENCES users(id),
  amount              BIGINT NOT NULL,
  currency            TEXT NOT NULL DEFAULT 'INR',
  status              TEXT NOT NULL CHECK (status IN ('PAID','UNSUCCESSFUL','MANUAL_REVIEW')),
  provider            TEXT,
  transaction_id      TEXT,
  utr                 TEXT,
  received_from       TEXT,
  purpose             TEXT,
  payment_time        BIGINT,
  updated_balance     BIGINT,
  verification_source TEXT NOT NULL,               -- GMAIL_FAMAPP | PROVIDER_WEBHOOK | MERCHANT_FORWARDER | MANUAL_ADMIN
  verified_at         BIGINT NOT NULL,
  created_at          BIGINT NOT NULL
);
CREATE INDEX ix_payments_user  ON payments (user_id, created_at DESC);
CREATE INDEX ix_payments_order ON payments (order_id);

CREATE TABLE gmail_payment_messages (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          BIGINT NOT NULL REFERENCES users(id),
  gmail_message_id TEXT NOT NULL,
  gmail_thread_id  TEXT,
  sender           TEXT,
  provider         TEXT,
  amount           BIGINT,
  transaction_id   TEXT,
  utr              TEXT,
  received_from    TEXT,
  purpose          TEXT,
  updated_balance  BIGINT,
  payment_time     BIGINT,
  result           TEXT NOT NULL,
  order_id         TEXT,
  created_at       BIGINT NOT NULL
);
CREATE UNIQUE INDEX ux_gmail_msg ON gmail_payment_messages (user_id, gmail_message_id);

CREATE TABLE payment_matches (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id         TEXT NOT NULL REFERENCES orders(id),
  gmail_message_id TEXT,
  match_result     TEXT NOT NULL,                  -- matched | manual_review | rejected
  reason           TEXT,
  created_at       BIGINT NOT NULL
);
CREATE INDEX ix_matches_order ON payment_matches (order_id);

CREATE TABLE payment_audit_logs (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   TEXT,
  admin_id   BIGINT,
  action     TEXT NOT NULL,
  reason     TEXT,
  ip         TEXT,
  metadata   TEXT,
  created_at BIGINT NOT NULL
);
CREATE INDEX ix_payment_audit_order ON payment_audit_logs (order_id);
